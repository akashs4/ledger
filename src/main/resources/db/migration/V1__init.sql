CREATE TABLE ACCOUNTS
(
    ID           UUID PRIMARY KEY,
    NAME         TEXT        NOT NULL,
    ACCOUNT_TYPE TEXT        NOT NULL DEFAULT 'USER' CHECK (ACCOUNT_TYPE IN ('SYSTEM', 'USER')),
    CREATED_AT   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX ACCOUNTS_SINGLE_SYSTEM_IDX ON ACCOUNTS (ACCOUNT_TYPE) WHERE ACCOUNT_TYPE = 'SYSTEM';

CREATE TABLE TRANSFERS
(
    ID               UUID PRIMARY KEY,
    IDEMPOTENCY_KEY  TEXT        NOT NULL UNIQUE,
    FROM_ACCOUNT_ID  UUID        NOT NULL REFERENCES ACCOUNTS (ID),
    TO_ACCOUNT_ID    UUID        NOT NULL REFERENCES ACCOUNTS (ID),
    AMOUNT_MINOR     BIGINT      NOT NULL CHECK (AMOUNT_MINOR > 0),
    STATUS           TEXT        NOT NULL DEFAULT 'POSTED' CHECK (STATUS IN ('POSTED', 'REJECTED')),
    REJECTION_REASON TEXT,
    CREATED_AT       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (FROM_ACCOUNT_ID <> TO_ACCOUNT_ID),
    CHECK ((STATUS = 'REJECTED') = (REJECTION_REASON IS NOT NULL))
);

CREATE INDEX TRANSFERS_FROM_ACCOUNT_IDX ON TRANSFERS (FROM_ACCOUNT_ID, CREATED_AT, ID);
CREATE INDEX TRANSFERS_TO_ACCOUNT_IDX ON TRANSFERS (TO_ACCOUNT_ID, CREATED_AT, ID);

CREATE TABLE BALANCES
(
    ACCOUNT_ID    UUID PRIMARY KEY REFERENCES ACCOUNTS (ID),
    BALANCE_MINOR BIGINT      NOT NULL DEFAULT 0,
    LAST_UPDATED  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

